#pragma once
// ============================================================
// Flips3D —— 3D 翻转框架（M3.5）
// 职责：
//   1. flip23：两个四面体共享面 → 三个共享边的四面体（2-3 翻转）
//   2. flip32：三个四面体共享边 → 两个共享面的四面体（3-2 翻转）
//   3. restoreDelaunay：Lawson 局部 Delaunay 恢复（迭代 flip23 消除违规面）
//   4. recoverEdgeByFlips：约束边恢复（让目标边成为网格边）
// 这是 3D 的关键架构补缺：M2 手动重建（insertConstrainedPoint）会破坏
// Delaunay 性，导致后续 Delaunay 插入不可靠；翻转能把网格局部恢复成
// Delaunay，从而让边界恢复/细化/质量三个问题同时受益。
//
// ------------------------------------------------------------
// ★ 3D 翻转修复必须带「不恶化」护栏（重要，勿删）★
// ------------------------------------------------------------
// 2D 的 Lawson 翻转**保证**每次 incircle 翻转都严格改善 Delaunay 性，
// 故必然终止于 Delaunay 三角化。**3D 没有这个性质**：3D 翻转图存在环，
// 单次 flip23 可能让局部违规数**增加**。这是 3D 的固有困难，不是实现 bug。
//
// 实测（退化输入：立方体六面各加 3×3 规则格点，大量精确共球）：
//   未加护栏：37 次**几何合法**的 flip23（均通过体积守恒 + validate），
//             但违规面 61 → 90，**单调恶化**。
//   加护栏后：只保留真正改善的 1 次，违规面 61 → 60。
// 逐面诊断显示单个 flip 的合法性判据无误（18 个违规面里 16 个因
// "degenerate new tet"、2 个因体积失配 rel≥0.25 被**正确**拒绝），
// 问题在「该不该翻」而非「翻得对不对」。
//
// 因此 restoreDelaunay 的实现是「**试翻 + 只接受严格改善**」：
// 在副本上 flip23，比较全局违规数（countLocalViolations），只有严格减少
// 才应用。这与论文 §8 的 "节点插入无法成功时退回（译意）"
// 同一精神。副作用是违规数单调递减 → 循环必然终止且保证不恶化。
//
// 另：flip23 额外校验 Joe 条件（新边 (d,e2) 不得已存在，否则产生非流形边），
// 且所有结构判据统一用 orient3dSoS / insphereSoS（与调用方同源，避免
// 两套符号体系在退化处矛盾）。
// ------------------------------------------------------------
//
// ------------------------------------------------------------
// 三条路线的分工（框架总览）
//   A. 细分路线（已实现，稳定）：recoverConstraintEdges 插入中点，
//      把断边一分为二递归处理。缺点是**必然新增顶点**，且对平面面
//      无法换对角线（现已用 edgeSatisfied 的「三角形覆盖」判据规避）。
//   B. 翻转路线（已接入，默认关闭）：recoverEdgeByFlips 用局部 2-3 翻转把
//      目标边直接翻成网格边，**不新增顶点**。实测只在「边缺失且 cavity
//      星形」的构型上有效（随机顶点对约 15% 命中）；对 cube 等用例的断边
//      **无效**（被约束面阻挡 / 腔非星形）。故当前定位是**能力储备**：
//      后续要控制 Steiner 点数（而非收敛性）时才值得开启。
//   C. 回退：B 失败（被约束面阻挡 / 近退化 / 翻不动）时退回 A 的细分，
//      保证功能不退步 —— 与原有实现「差不多」。
// ============================================================

#include <cstdint>
#include <string>
#include <unordered_set>

#include "mesh/data/TetMesh3D.h"

namespace mesher {

/// 2-3 翻转：t1、t2 共享面 {a,b,c}（对侧 d、e），替换为 3 个共享边 (d,e) 的四面体。
/// 要求 d、e 在共享面两侧（线段 de 穿过面）。成功返回 true。
bool flip23(TetMesh3D& mesh, int t1, int t2, std::string* error);

/// 3-2 翻转：三个四面体共享边 (d,e)，替换为 2 个共享面 (a,b,c) 的四面体。
/// 成功返回 true。
bool flip32(TetMesh3D& mesh, int t1, int t2, int t3, std::string* error);

/// Lawson 局部 Delaunay 恢复：迭代 2-3 翻转直到所有内部面满足 Delaunay 或达上限。
/// 返回执行的翻转次数。
///
/// ★ 带「不恶化」护栏 ★：每次候选 flip23 先在副本上试翻，只有全局违规数
/// **严格减少**才真正应用（见文件头说明）。因此返回的翻转次数一定 ≤ 无护栏
/// 版本，且**保证违规数不增加**。代价是每次候选多一次 O(T) 计数 + 一次
/// O(T) 拷贝；当前网格规模可接受。
int restoreDelaunay(TetMesh3D& mesh, int maxFlips = 200000);

/// 约束边恢复（翻转路线）：尝试用局部翻转把 (u,v) 变成网格边，**不新增顶点**。
/// ------------------------------------------------------------
/// 算法（3D 标准边恢复的两步）：
///   1. 若 (u,v) 已是网格边 → 直接成功（0 次翻转）。
///   2. 否则：若存在一条**同时与 u、v 相邻**的顶点 w（即 (u,w)、(v,w) 都是网格边，
///      且 u,v,w 共面于某个网格面），做 2-3 翻转把 (u,v) 引入。
///      更一般地：找出所有含 u 但不含 v 的四面体，若其「对 u 的对侧面」都能
///      与 v 组成合法翻转，则逐个 2-3 翻转 —— 最终 (u,v) 出现。
/// blockedFaces：约束面屏障（翻转不得跨越，否则会毁掉已恢复的表面）。
///
/// 返回：已成功（(u,v) 成为网格边）⇒ true；否则 false（调用方应回退到中点细分）。
/// outFlips：实际执行的翻转次数（诊断用）。
bool recoverEdgeByFlips(TetMesh3D& mesh, int u, int v,
                        const std::unordered_set<uint64_t>& blockedFaces,
                        int* outFlips, std::string* error);

} // namespace mesher
